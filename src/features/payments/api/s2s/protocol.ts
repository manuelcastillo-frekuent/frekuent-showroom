/**
 * Contract between the showroom screen and the services it talks to directly
 * (there is no BFF). PROVISIONAL: the real endpoints are not defined yet, so
 * this mirrors what ../showroom-bff simulates. docs/s2s-protocol.md describes
 * it; keep both, and the simulator's copy, in sync.
 *
 * - HTTP to the payments service: open the sale, poll its status, cancel it.
 * - Machine channel (WebSocket today, maybe MQTT): the dispense order in, the
 *   dispense result out.
 */

export type Spot = 'pro' | 'compact' | 'mini';

/** `POST {apiUrl}/sales` */
export interface SaleRequestBody {
  /** Generated by the screen so a retried POST does not open a second payment. */
  requestId: string;
  spot: Spot;
  productCode: string;
  amountCents: number;
}

/** 201 response to `POST /sales`. The field name is still to be confirmed. */
export interface SaleResponse {
  paymentId: string;
}

/** `GET {apiUrl}/payments/{paymentId}` → `{ paymentId, status }` */
export const PAYMENT_STATUSES = [
  'waiting_tap',
  'authorising',
  'approved',
  'completed',
  'declined',
  'rejected',
  'timeout',
  'cancelled',
] as const;
export type PaymentStatus = (typeof PAYMENT_STATUSES)[number];

export interface StatusResponse {
  paymentId: string;
  status: PaymentStatus;
}

/** Machine channel, screen → server */
export type ClientMessage = { type: 'dispense_result'; paymentId: string; success: boolean };

/**
 * Machine channel, server → screen. One order carries both the approval and
 * the instruction to dispense (it replaces payment_approved + dispense).
 */
export type ServerMessage = {
  type: 'dispense';
  paymentId: string;
  productCode: string;
  authCode: string;
  method: 'card' | 'wallet';
};

type Field = 'string' | readonly string[];

function check(data: unknown, shape: Record<string, Field>, what: string) {
  if (typeof data !== 'object' || data === null) throw new Error(`${what}: not an object`);
  const record = data as Record<string, unknown>;
  for (const [key, field] of Object.entries(shape)) {
    const value = record[key];
    const ok = field === 'string' ? typeof value === 'string' : field.includes(value as string);
    if (!ok) throw new Error(`${what}: bad field ${key}`);
  }
  return record;
}

/** Parses one frame from the machine channel; throws if it breaks the contract. */
export function parseServerMessage(raw: unknown): ServerMessage {
  const data: unknown = JSON.parse(String(raw));
  const type = (data as { type?: unknown } | null)?.type;
  if (type !== 'dispense') throw new Error(`Unknown type: ${String(type)}`);
  check(
    data,
    { paymentId: 'string', productCode: 'string', authCode: 'string', method: ['card', 'wallet'] },
    'dispense',
  );
  return data as ServerMessage;
}

export function parseSaleResponse(data: unknown): SaleResponse {
  return check(data, { paymentId: 'string' }, 'sale') as unknown as SaleResponse;
}

export function parseStatusResponse(data: unknown): StatusResponse {
  return check(
    data,
    { paymentId: 'string', status: PAYMENT_STATUSES },
    'status',
  ) as unknown as StatusResponse;
}
